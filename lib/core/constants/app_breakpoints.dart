/// Material 3 Responsive Breakpoints and Layout Max Widths.
class AppBreakpoints {
  /// Mobile portrait / compact screens
  static const double compact = 600.0;

  /// Tablets portrait / medium foldables
  static const double medium = 840.0;

  /// Large screens / desktop / web
  static const double expanded = 1200.0;

  /// Threshold to switch between bottom navigation and navigation rail
  static const double navigationRailBreakpoint = 720.0;

  /// Max width constraint for forms and detail inputs
  static const double maxFormWidth = 640.0;

  /// Max width constraint for lists, cards and dashboards
  static const double maxContentWidth = 960.0;
}
